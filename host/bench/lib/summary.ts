import fs from "node:fs";
import path from "node:path";

import { type MetricResult, type WorkloadResult, fmt } from "./harness.ts";

/** On-disk result file (`results/<engine>-<suite>-<timestamp>.json`) */
export type RunFile = {
  /** result format version */
  version: 1;
  engine: string;
  suite: string;
  quick: boolean;
  /** false while a run is in progress or when it was interrupted */
  complete?: boolean;
  /** workload name filter of the run (`--filter`), if any */
  filter?: string | null;
  /** engines alternated slice by slice in the same process (`--interleave`) */
  interleaved?: string[] | null;
  /** free-form caveat shown next to the run in the summary (`--note`) */
  note?: string | null;
  /** iteration override of the run (`--iterations`), if any */
  iterations?: number | null;
  startedAt: string;
  finishedAt: string;
  machine: Record<string, unknown>;
  workloads: WorkloadResult[];
};

/** Engine variants in column order; ratios are relative to `native` */
const ENGINES = [
  "native-prev",
  "native",
  "native-prev-virtiofs",
  "native-virtiofs",
];

/** Metric shown per workload: guest-side timing wins over host wall time */
function shownMetrics(w: WorkloadResult): [string, MetricResult][] {
  const entries = Object.entries(w.metrics);
  const hasGuest = entries.some(([k]) => k === "guestMs" || k === "requestMs");
  return entries.filter(([k]) => !(k === "wallMs" && hasGuest));
}

function cell(m: MetricResult | undefined): string {
  if (!m) return "-";
  return `${fmt(m.stats.median)} (${fmt(m.stats.p95)})`;
}

function ratio(
  base: MetricResult | undefined,
  other: MetricResult | undefined,
): string {
  if (!base || !other || !base.stats.median) return "-";
  return `${(other.stats.median / base.stats.median).toFixed(2)}x`;
}

function costCell(w: WorkloadResult | undefined): string {
  if (!w?.cost) return "-";
  const iterations = Math.max(1, w.iterations);
  const cpu = w.cost.reduce((sum, c) => sum + (c.cpuMs ?? 0), 0) / iterations;
  const parts = w.cost.map(
    (c) =>
      `${c.role} ${fmt((c.cpuMs ?? 0) / iterations)}ms/${fmt(c.rssPeakMB ?? NaN)}MB`,
  );
  return `${fmt(cpu)} ms (${parts.join(", ")})`;
}

function machineLine(run: RunFile): string {
  const m = run.machine;
  return `${run.engine}${run.note ? " (see note)" : ""}: ${run.startedAt}${run.quick ? " (quick)" : ""}${run.complete === false ? " (incomplete)" : ""}${run.filter ? ` (filter ${run.filter})` : ""}${run.interleaved ? ` (interleaved ${run.interleaved.join("/")})` : ""}, ${m.cpuModel} x${m.cpuCount}, ${m.platform} ${m.productVersion ?? m.osRelease}, node ${m.node}, ${m.qemu ?? "qemu ?"}${m.virtiofsEnv ? ` (GONDOLIN_VIRTIOFS=${m.virtiofsEnv}, ${m.qemuPath})` : ""}${m.nativeBin ? `, bin ${m.nativeBin}` : ""}, load ${Array.isArray(m.loadAvg) ? m.loadAvg[0] : "?"}${Array.isArray(m.loadAvgEnd) ? `→${m.loadAvgEnd[0]}` : ""}, image ${m.image}, commit ${m.gitCommit}${m.gitDirty ? "+dirty" : ""}`;
}

export function loadRuns(dir: string): RunFile[] {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .map(
      (f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")) as RunFile,
    )
    .filter((r) => r.version === 1);
}

/** Latest complete run per engine and suite; quick or partial runs only if nothing else exists */
function latest(
  runs: RunFile[],
  engine: string,
  suite: string,
): RunFile | undefined {
  const partial = (r: RunFile) =>
    Number(r.quick) +
    Number(Boolean(r.filter) || r.iterations != null || r.complete === false);
  const candidates = runs
    .filter((r) => r.engine === engine && r.suite === suite)
    .sort(
      (a, b) =>
        partial(a) - partial(b) || b.startedAt.localeCompare(a.startedAt),
    );
  return candidates[0];
}

export function renderSummary(runs: RunFile[]): string {
  const suites = [...new Set(runs.map((r) => r.suite))].sort();
  const lines = [
    "# Benchmark summary",
    "",
    "Generated by `node bench/run.ts` from the latest run per engine and suite in this directory.",
    "Cells are `median (p95)`. Ratios are variant / native: below 1 is better for `ms`, above 1 is better for `MB/s` and `ops/s`.",
    "Cost is cpu time per iteration summed over the host process and engine processes (`role cpu/peak rss`).",
    "",
  ];
  for (const suite of suites) {
    // The newest interleaved run set wins as a whole, so engines are never
    // compared across runs taken at different times.
    const newest = ENGINES.map((e) => latest(runs, e, suite))
      .filter((r): r is RunFile => Boolean(r))
      .sort((a, b) => b.startedAt.localeCompare(a.startedAt))[0];
    const group = newest?.interleaved
      ? runs.filter(
          (r) => r.suite === suite && r.startedAt === newest.startedAt,
        )
      : null;
    const pick = (e: string) =>
      group ? group.find((r) => r.engine === e) : latest(runs, e, suite);
    const engines = ENGINES.filter((e) => pick(e));
    const byEngine = Object.fromEntries(engines.map((e) => [e, pick(e)!]));
    const others = engines.includes("native")
      ? engines.filter((e) => e !== "native")
      : [];
    lines.push(`## ${suite}`, "");
    for (const run of Object.values(byEngine))
      lines.push(`- ${machineLine(run)}`);
    for (const run of Object.values(byEngine)) {
      if (run.note) lines.push("", `> **${run.engine}: ${run.note}**`);
    }
    lines.push(
      "",
      `| ${["workload", "metric", "unit", ...engines, ...others.map((e) => `${e} / native`), `load ${engines.join(" / ")}`].join(" | ")} |`,
      `|${"---|".repeat(4 + engines.length + others.length)}`,
    );
    const names: string[] = [];
    for (const run of Object.values(byEngine))
      for (const w of run.workloads)
        if (!names.includes(w.name)) names.push(w.name);
    const costRows: string[] = [];
    for (const name of names) {
      const ws = engines.map((e) =>
        byEngine[e].workloads.find((w) => w.name === name),
      );
      const base = byEngine.native?.workloads.find((w) => w.name === name);
      const metricNames = new Set(
        ws.flatMap((w) => (w ? shownMetrics(w) : [])).map(([k]) => k),
      );
      let first = true;
      for (const metric of metricNames) {
        const ms = ws.map((w) => w?.metrics[metric]);
        const unit = ms.find(Boolean)?.unit ?? "";
        const ratios = others.map((e) =>
          ratio(base?.metrics[metric], ws[engines.indexOf(e)]?.metrics[metric]),
        );
        const load = first ? ws.map((w) => w?.loadAvg ?? "-").join(" / ") : "";
        first = false;
        lines.push(
          `| ${[name, metric, unit, ...ms.map(cell), ...ratios, load].join(" | ")} |`,
        );
      }
      const errors = ws
        .map((w, i) => w?.error && `${engines[i]}: ${w.error}`)
        .filter(Boolean);
      if (errors.length > 0)
        lines.push(
          `| ${name} | error | | ${errors.join("; ").replace(/\|/g, "/")} |${" |".repeat(engines.length + others.length)}`,
        );
      if (ws.some((w) => w?.cost))
        costRows.push(`| ${name} | ${ws.map(costCell).join(" | ")} |`);
    }
    if (costRows.length > 0) {
      lines.push(
        "",
        "Host cost per iteration:",
        "",
        `| workload | ${engines.join(" | ")} |`,
        `|${"---|".repeat(1 + engines.length)}`,
        ...costRows,
      );
    }
    lines.push("");
  }
  return lines.join("\n");
}
